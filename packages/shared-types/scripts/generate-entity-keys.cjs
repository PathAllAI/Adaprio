// Generates src/entity-keys.generated.ts from the frozen MVP taxonomy.
// Run: node scripts/generate-entity-keys.cjs
//
// SOURCE OF TRUTH NOTE: this key list must stay byte-identical to the
// `KEYS` array in packages/db/seed/generate-entity-registry-seed.js.
// There are two generators (one emits SQL seed data, one emits a TS union
// type) because packages/shared-types has zero runtime dependencies and
// cannot import a .js file from packages/db (see Ch 33.1.3 — packages/db
// is import-free). Until these are unified under a single generator with
// two emitters, changing one requires changing the other in the same PR —
// this is flagged as a known maintenance risk, not a settled design.
"use strict";
const fs = require("fs");
const path = require("path");

const KEYS = [
  ["identity", "identity.name"],
  ["identity", "identity.nickname"],
  ["identity", "identity.language"],
  ["identity", "identity.timezone"],
  ["identity", "identity.birth_date"],
  ["identity", "identity.cultural_background"],

  ["location", "location.country"],
  ["location", "location.city"],
  ["location", "location.region"],
  ["location", "location.residence"],
  ["location", "location.previous"],

  ["employment", "employment.organization"],
  ["employment", "employment.role"],
  ["employment", "employment.industry"],
  ["employment", "employment.status"],
  ["employment", "employment.work_style"],
  ["employment", "employment.experience"],

  ["education", "education.institution"],
  ["education", "education.field"],
  ["education", "education.degree"],
  ["education", "education.level"],
  ["education", "education.status"],

  ["skill", "skill.technical"],
  ["skill", "skill.language"],
  ["skill", "skill.professional"],
  ["skill", "skill.learning"],

  ["project", "project.name"],
  ["project", "project.type"],
  ["project", "project.status"],
  ["project", "project.goal"],
  ["project", "project.technology"],

  ["goal", "goal.personal"],
  ["goal", "goal.career"],
  ["goal", "goal.education"],
  ["goal", "goal.financial"],
  ["goal", "goal.health"],
  ["goal", "goal.timeline"],

  ["preference", "preference.general"],
  ["preference", "preference.communication_style"],
  ["preference", "preference.technology"],
  ["preference", "preference.food"],
  ["preference", "preference.entertainment"],
  ["preference", "preference.learning_style"],

  ["ai", "ai.response_style"],
  ["ai", "ai.workflow_preference"],
  ["ai", "ai.model_preference"],

  ["relationship", "relationship.person"],
  ["relationship", "relationship.role"],
  ["relationship", "relationship.organization"],

  ["task", "task.current"],
  ["task", "task.deadline"],
  ["task", "task.status"],
  ["event", "event.personal"],
  ["event", "event.professional"],
  ["event", "event.deadline"],

  ["technology", "technology.device"],
  ["technology", "technology.software"],
  ["technology", "technology.account"],

  ["finance", "finance.goal"],

  ["health", "health.preference"],
];

if (KEYS.length !== 60) {
  throw new Error(`Expected exactly 60 keys, got ${KEYS.length}`);
}

const domains = [...new Set(KEYS.map(([d]) => d))].sort();

const lines = [];
lines.push("// AUTO-GENERATED by scripts/generate-entity-keys.cjs — do not hand-edit.");
lines.push("// Source of truth: the frozen MVP v1.0 taxonomy (Handbook Ch 08, Ch 25-A).");
lines.push("// Regenerate with: node scripts/generate-entity-keys.cjs");
lines.push("");
lines.push(`export const MEMORY_DOMAINS = [${domains.map((d) => `'${d}'`).join(", ")}] as const;`);
lines.push("export type MemoryDomain = typeof MEMORY_DOMAINS[number];");
lines.push("");
lines.push("export const ENTITY_KEYS = [");
for (const [, key] of KEYS) {
  lines.push(`  '${key}',`);
}
lines.push("] as const;");
lines.push("");
lines.push("/**");
lines.push(" * Union of all 60 frozen entity keys (Handbook Ch 08). Enforced at the");
lines.push(" * database layer by a foreign key to entity_key_registry — this type is a");
lines.push(" * compile-time mirror for catching typos before a request ever reaches the");
lines.push(" * DB, not a replacement for the runtime FK constraint.");
lines.push(" */");
lines.push("export type EntityKey = typeof ENTITY_KEYS[number];");
lines.push("");
lines.push("export const ENTITY_KEYS_BY_DOMAIN: Record<MemoryDomain, EntityKey[]> = {");
for (const domain of domains) {
  const keysForDomain = KEYS.filter(([d]) => d === domain).map(([, k]) => `'${k}'`);
  lines.push(`  ${domain}: [${keysForDomain.join(", ")}],`);
}
lines.push("};");
lines.push("");

fs.writeFileSync(path.join(__dirname, "..", "src", "entity-keys.generated.ts"), lines.join("\n"));
console.log(`Wrote ${KEYS.length} entity keys across ${domains.length} domains.`);
